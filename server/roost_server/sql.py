"""Storage for the roost package outside Cloudflare.

roost talks to two kinds of SQL, both written in SQLite's dialect:

- the directory (D1 on the Worker): async `first/all/run/batch`;
- per-account and sequencer storage (Durable Object SQLite on the Worker):
  synchronous `exec(query, *params) -> list[dict]`.

A backend offers both. `SqliteBackend` keeps one database file per account
(the Durable Object boundary, on disk) for self-hosting and tests.
`PostgresBackend` keeps one schema per account in a single database, which is
what FastAPI Cloud offers (Neon or Supabase, as DATABASE_URL). Either way an
account call runs in one transaction under a per-account lock, so writes to
one repo stay serialized the way a Durable Object serializes them, and a
call's firehose events commit with its repo writes.
"""

import asyncio
import hashlib
import re
import sqlite3
import threading
from contextlib import contextmanager
from pathlib import Path

# A Durable Object id on the Worker is 64 hex digits; ids minted here are 32.
ACCOUNT_ID = re.compile(r"^[0-9a-f]{32,64}$")
SEQUENCER_SCHEMA = "roost_sequencer"


def check_account_id(do_id: str) -> str:
    if not isinstance(do_id, str) or not ACCOUNT_ID.match(do_id):
        raise ValueError(f"Invalid account id: {do_id!r}")
    return do_id


# SQLite -> Postgres

_LITERAL = re.compile(r"('(?:[^']|'')*')")
# Whole-statement rewrites, matched before literals are set aside.
_STATEMENTS = [
    (re.compile(r"^\s*PRAGMA\s+table_info\((\w+)\)\s*$", re.I),
     r"SELECT column_name AS name FROM information_schema.columns "
     r"WHERE table_schema = current_schema() AND table_name = '\1'"),
    (re.compile(r"\bFROM\s+sqlite_master\s+WHERE\s+type\s*=\s*'table'\s+AND\s+name\s*=", re.I),
     "FROM information_schema.tables WHERE table_schema = current_schema() AND table_name ="),
]
# Column types, in CREATE TABLE / ALTER TABLE only.
_DDL = re.compile(r"^\s*(CREATE|ALTER)\s+TABLE\b", re.I)
_TYPES = [
    (re.compile(r"\bINTEGER\s+PRIMARY\s+KEY(\s+AUTOINCREMENT)?", re.I), "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"),
    (re.compile(r"\bINTEGER\b", re.I), "BIGINT"),
    (re.compile(r"\bBLOB\b", re.I), "BYTEA"),
    # Bytewise ordering, as SQLite compares TEXT: rkeys, cids and cursors depend on it.
    (re.compile(r"\bTEXT\b", re.I), 'TEXT COLLATE "C"'),
]
# Anywhere outside a literal.
_EXPRESSIONS = [
    (re.compile(r"datetime\('now'\)", re.I), "to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')"),
    (re.compile(r"\bjson_each\(([^()]+)\)", re.I), r"json_array_elements_text((\1)::json) AS value"),
]
_cache: dict[str, str] = {}


def to_postgres(query: str) -> str:
    """One SQLite statement as Postgres, with psycopg placeholders.

    Only the SQLite-isms roost uses are rewritten; string literals are kept
    (their % escaped, as psycopg requires)."""
    found = _cache.get(query)
    if found is not None:
        return found
    text = query
    for pattern, replacement in _STATEMENTS + _EXPRESSIONS:
        text = pattern.sub(replacement, text)
    ddl = bool(_DDL.match(text))
    parts = _LITERAL.split(text)
    for index in range(0, len(parts), 2):  # outside literals
        part = parts[index]
        if ddl:
            for pattern, replacement in _TYPES:
                part = pattern.sub(replacement, part)
        parts[index] = part.replace("?", "\0")
    translated = "".join(parts).replace("%", "%%").replace("\0", "%s")
    _cache[query] = translated
    return translated


def _pg_param(value):
    # SQLite has no booleans; roost passes True/False for INTEGER columns.
    if isinstance(value, bool):
        return int(value)
    if isinstance(value, (bytearray, memoryview)):
        return bytes(value)
    return value


class UniqueConstraintError(Exception):
    """A Postgres unique violation, worded as SQLite and D1 word theirs
    ("UNIQUE constraint failed: ..."), which is what roost checks for."""


@contextmanager
def _sqlite_wording():
    from psycopg import errors

    try:
        yield
    except errors.UniqueViolation as exc:
        raise UniqueConstraintError(f"UNIQUE constraint failed: {exc.diag.constraint_name}") from exc


def _lock_key(name: str) -> int:
    return int.from_bytes(hashlib.sha256(name.encode()).digest()[:8], "big", signed=True)


# SQLite

def _sqlite_connect(path) -> sqlite3.Connection:
    connection = sqlite3.connect(path, isolation_level=None, check_same_thread=False)
    connection.row_factory = sqlite3.Row
    if path != ":memory:":
        connection.execute("PRAGMA journal_mode=WAL")
    connection.execute("PRAGMA busy_timeout=5000")
    return connection


def _sqlite_rows(cursor) -> list[dict]:
    return [dict(row) for row in cursor.fetchall()]


class SqliteSql:
    """exec() on one SQLite connection; `begin` runs before the first statement."""

    def __init__(self, connection: sqlite3.Connection, begin=None):
        self._connection = connection
        self._begin = begin

    def exec(self, query: str, *params) -> list[dict]:
        if self._begin is not None:
            begin, self._begin = self._begin, None
            begin()
        return _sqlite_rows(self._connection.execute(query, params))


class SqliteDirectory:
    """D1 on one SQLite file. Statements are microseconds, so they run inline."""

    def __init__(self, connection: sqlite3.Connection):
        self._connection = connection
        self._lock = threading.Lock()

    def _execute(self, sql, params):
        with self._lock:
            return self._connection.execute(sql, params)

    async def first(self, sql: str, *params) -> dict | None:
        rows = _sqlite_rows(self._execute(sql, params))
        return rows[0] if rows else None

    async def all(self, sql: str, *params) -> list[dict]:
        return _sqlite_rows(self._execute(sql, params))

    async def run(self, sql: str, *params) -> int:
        return self._execute(sql, params).rowcount

    async def batch(self, statements) -> None:
        with self._lock:
            self._connection.execute("BEGIN")
            try:
                for sql, params in statements:
                    self._connection.execute(sql, params)
            except BaseException:
                self._connection.execute("ROLLBACK")
                raise
            self._connection.execute("COMMIT")


class SqliteBackend:
    """`root/directory.sqlite3`, `root/sequencer.sqlite3`, `root/accounts/<id>.sqlite3`;
    root ":memory:" keeps everything in memory (tests)."""

    def __init__(self, root: str):
        self._memory = root == ":memory:"
        self._root = None if self._memory else Path(root)
        if self._root:
            (self._root / "accounts").mkdir(parents=True, exist_ok=True)
        self.directory = SqliteDirectory(self._connect("directory"))
        self._sequencer = self._connect("sequencer")
        self._sequencer_lock = threading.Lock()
        self._accounts: dict[str, tuple[sqlite3.Connection, threading.Lock]] = {}
        self._accounts_lock = threading.Lock()

    def _connect(self, name: str) -> sqlite3.Connection:
        return _sqlite_connect(":memory:" if self._memory else str(self._root / f"{name}.sqlite3"))

    def _account(self, do_id: str):
        with self._accounts_lock:
            found = self._accounts.get(do_id)
            if found is None:
                found = self._accounts[do_id] = (self._connect(f"accounts/{do_id}"), threading.Lock())
            return found

    @contextmanager
    def account_session(self, do_id: str):
        """(account_sql, sequencer_sql) in one transaction each; the sequencer's
        lock is taken on its first statement and held to commit, so events
        commit in seq order."""
        connection, lock = self._account(check_account_id(do_id))
        held = []

        def begin_sequencer():
            self._sequencer_lock.acquire()
            held.append(True)
            self._sequencer.execute("BEGIN IMMEDIATE")

        with lock:
            connection.execute("BEGIN IMMEDIATE")
            try:
                yield SqliteSql(connection), SqliteSql(self._sequencer, begin=begin_sequencer)
            except BaseException:
                connection.execute("ROLLBACK")
                if held:
                    self._sequencer.execute("ROLLBACK")
                raise
            else:
                if held:
                    self._sequencer.execute("COMMIT")
                connection.execute("COMMIT")
            finally:
                if held:
                    self._sequencer_lock.release()

    @contextmanager
    def sequencer_session(self):
        with self._sequencer_lock:
            yield SqliteSql(self._sequencer)

    def close(self) -> None:
        for connection, _ in self._accounts.values():
            connection.close()
        self._sequencer.close()


# Postgres

class PostgresSql:
    """exec() on a connection shared by the schemas of one transaction: switches
    search_path when needed and takes `lock` before its first statement."""

    def __init__(self, session: "PostgresSession", schema: str, lock: int | None = None):
        self._session = session
        self._schema = schema
        self._lock = lock

    def exec(self, query: str, *params) -> list[dict]:
        session = self._session
        if self._lock is not None:
            lock, self._lock = self._lock, None
            session.execute("SELECT pg_advisory_xact_lock(%s)", (lock,))
        if session.schema != self._schema:
            session.execute(f'SET LOCAL search_path TO "{self._schema}"')
            session.schema = self._schema
        return session.rows(to_postgres(query), tuple(_pg_param(param) for param in params))


class PostgresSession:
    def __init__(self, connection):
        self.connection = connection
        self.schema = None

    def execute(self, sql: str, params=()):
        return self.connection.execute(sql, params)

    def rows(self, sql: str, params) -> list[dict]:
        with _sqlite_wording():
            cursor = self.connection.execute(sql, params)
        return cursor.fetchall() if cursor.description else []


class PostgresDirectory:
    """D1 on Postgres (the public schema, or the URL's search_path); calls run
    in a worker thread so the event loop never waits on the network."""

    def __init__(self, pool):
        self._pool = pool

    def _run(self, statements):
        with self._pool.connection() as connection, _sqlite_wording():
            result = None
            for sql, params in statements:
                result = connection.execute(to_postgres(sql), tuple(_pg_param(param) for param in params))
            return (result.fetchall() if result.description else [], result.rowcount)

    async def _one(self, sql, params):
        return await asyncio.to_thread(self._run, [(sql, params)])

    async def first(self, sql: str, *params) -> dict | None:
        rows, _ = await self._one(sql, params)
        return rows[0] if rows else None

    async def all(self, sql: str, *params) -> list[dict]:
        return (await self._one(sql, params))[0]

    async def run(self, sql: str, *params) -> int:
        return (await self._one(sql, params))[1]

    async def batch(self, statements) -> None:
        if statements:
            await asyncio.to_thread(self._run, [(sql, list(params)) for sql, params in statements])


class PostgresBackend:
    """One database: the directory in the default schema, the firehose in
    roost_sequencer, each account in its own schema account_<id>."""

    def __init__(self, url: str, max_connections: int = 10):
        from psycopg.rows import dict_row
        from psycopg_pool import ConnectionPool

        self._pool = ConnectionPool(
            url, min_size=1, max_size=max_connections, open=True,
            kwargs={"row_factory": dict_row, "prepare_threshold": None},
        )
        self.directory = PostgresDirectory(self._pool)
        with self._pool.connection() as connection:
            connection.execute(f'CREATE SCHEMA IF NOT EXISTS "{SEQUENCER_SCHEMA}"')

    @contextmanager
    def account_session(self, do_id: str):
        schema = f"account_{check_account_id(do_id)}"
        with self._pool.connection() as connection:  # commits on success, rolls back on error
            session = PostgresSession(connection)
            session.execute("SELECT pg_advisory_xact_lock(%s)", (_lock_key(f"account:{do_id}"),))
            session.execute(f'CREATE SCHEMA IF NOT EXISTS "{schema}"')
            yield PostgresSql(session, schema), PostgresSql(session, SEQUENCER_SCHEMA, lock=_lock_key("sequencer"))

    @contextmanager
    def sequencer_session(self):
        with self._pool.connection() as connection:
            yield PostgresSql(PostgresSession(connection), SEQUENCER_SCHEMA)

    def close(self) -> None:
        self._pool.close()


def open_backend(database_url: str | None, data_dir: str | None):
    """DATABASE_URL (postgres://, postgresql://) wins; else SQLite under data_dir."""
    if database_url:
        if not database_url.startswith(("postgres://", "postgresql://")):
            raise ValueError("DATABASE_URL must be a postgres:// or postgresql:// URL")
        return PostgresBackend(database_url)
    if not data_dir:
        raise ValueError("Set DATABASE_URL (Postgres) or ROOST_DATA_DIR (SQLite directory)")
    return SqliteBackend(data_dir)
